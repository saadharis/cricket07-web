#!/usr/bin/env python3
"""
build_web.py — assemble the browser deployable of Cricket 07 from:
  - the engine files served by cricket07.dhaiwat.com (Dhaiwat10/cricket07-browser, MIT)
  - the enhancement layer from udeshvirk/cricket07-mac (enhance.js, names.js, real-names.json)

It reproduces exactly the page transformations the Electron wrapper applies at runtime
(main.js -> adapt()), plus one addition the wrapper does not need: coi-serviceworker,
which supplies the COOP/COEP headers GitHub Pages cannot set.

Run from the repo root:  python src/build_web.py
"""
import json, re, shutil, hashlib, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC  = ROOT / "src"
ENG  = SRC / "engine"
WRAP = SRC / "wrapper"

def read(p): return p.read_text(encoding="utf-8")
def write(p, s): p.write_text(s, encoding="utf-8"); print(f"  wrote {p.relative_to(ROOT)} ({len(s):,} chars)")

# ---------------------------------------------------------------- index.html
def build_index():
    text = read(ENG / "index.html")

    # 1. no web analytics — and the Cloudflare beacon would also break COEP isolation
    before = text
    text = re.sub(r"<!-- Cloudflare Web Analytics[\s\S]*?</script>\n?", "", text)
    text = re.sub(r"<script[^>]*static\.cloudflareinsights\.com[^>]*></script>\s*", "", text)
    assert "cloudflareinsights" not in text, "beacon removal failed"

    # 2. cross-origin isolation shim must be the very first script (GitHub Pages sends no COOP/COEP)
    assert '<script src="netplay.js"></script>' in text, "netplay anchor missing"
    text = text.replace(
        '<script src="netplay.js"></script>',
        '<script src="coi-serviceworker.min.js"></script>\n'
        '<script src="enhance.js"></script>\n'
        '<script src="names-web.js"></script>\n'
        '<script src="netplay.js"></script>',
    )
    return text

# ---------------------------------------------------------------- c07.js
def build_c07():
    text = read(ENG / "c07.js")
    # widescreen/stretch parity with the desktop app (same replacement as main.js adapt())
    pat = (r"canvas\.width = Math\.max\(640, Math\.round\(r\.width \* dpr\)\);\s*"
           r"canvas\.height = Math\.max\(480, Math\.round\(r\.height \* dpr\)\);")
    rep = ("canvas.height = Math.max(480, Math.round(r.height * dpr));\n"
           "  canvas.width = window.c07Enhance?.wide ? Math.max(640, Math.round(r.width * dpr)) "
           ": Math.max(640, Math.round(canvas.height * 4 / 3));")
    new, n = re.subn(pat, rep, text, count=1)
    assert n == 1, f"c07.js canvas patch matched {n} times"
    return new

# ---------------------------------------------------------------- names-web.js
def build_names():
    names_js = read(WRAP / "names.js")
    m = re.search(r"const PAGE_JS = `(async \(NAMES, mode\) => \{[\s\S]*?\})`;", names_js)
    assert m, "PAGE_JS not found in names.js"
    page_fn = m.group(1)
    data = json.loads(read(WRAP / "real-names.json"))
    count = len(data) if isinstance(data, list) else len(data.get("names", data))
    return f"""// Real player names, applied to Data/data.gob in OPFS.
// Ported verbatim from cricket07-mac/names.js (PAGE_JS) — it only uses
// navigator.storage.getDirectory(), so it runs unchanged in a plain browser tab.
(async () => {{
  const NAMES = {json.dumps(data)};
  const apply = {page_fn};
  // The game files must be in place first; the page reports 'no-game' until they are.
  let tries = 0;
  const run = async () => {{
    const r = await apply(NAMES, 'real');
    if (r === 'no-game' && tries++ < 60) {{ setTimeout(run, 3000); return; }}
    if (r === 'real') console.log('Cricket 07 web: real names applied (' + NAMES.length + ' players).');
  }};
  run();
}})();
"""

def main():
    print("building cricket07-web ...")
    write(ROOT / "index.html", build_index())
    write(ROOT / "c07.js", build_c07())
    write(ROOT / "names-web.js", build_names())
    shutil.copyfile(WRAP / "enhance.js", ROOT / "enhance.js")
    print(f"  copied enhance.js ({(ROOT/'enhance.js').stat().st_size:,} bytes)")

    # proof file: a clone can confirm it produced the identical deployed page
    h = hashlib.sha256((ROOT / "index.html").read_bytes()).hexdigest()
    w = hashlib.sha256((ROOT / "build/cricket07.wasm").read_bytes()).hexdigest()
    write(ROOT / "BUILD-PROOF.md",
          f"# Build proof\n\nGenerated by `python src/build_web.py`.\n\n"
          f"| file | sha256 |\n|---|---|\n"
          f"| index.html | `{h}` |\n| build/cricket07.wasm | `{w}` |\n")
    print("done.")

if __name__ == "__main__":
    sys.exit(main())
